// node tools/build_site.js [--fixtures] [--out _site]
// Builds the self-contained site GitHub Pages serves: the evaluator page, the data prebuilt by
// evaluator/wiki.js from the wiki's JSON and supplement/supplement.json, and the supplement itself.
// The page then needs nothing else: no wiki requests from visitors' browsers, so no CORS problem.
//
// The data is split per mod (evaluator/site_loader.js): data/swi.json, data/dabc.json, ... and a
// small data.js (the manifest plus the loader), so visitors download only the mods they enable.
// Every file the page references gets ?v=<content hash>, so a new build is never mixed with
// files the browser still caches from the previous one.
//
//   default     fetch the live wiki (server-side, so CORS does not apply): about 900 requests,
//               at most 4 at a time, one retry each, a User-Agent naming the project
//   --fixtures  use the recorded copy in tests/fixtures/wiki instead (for local checks)
//
// Mods are wiki.js's allowlist (SWI, DABC, RSP); nothing else is requested.
"use strict";
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const W = require("../evaluator/wiki.js");
const S = require("../evaluator/site_loader.js");
const { fixtureFetch } = require("./fixtures.js");

const ROOT = path.join(__dirname, "..");
const args = process.argv.slice(2);
const OUT = path.resolve(ROOT, args.includes("--out") ? args[args.indexOf("--out") + 1] : "_site");
const UA = "x4-ship-evaluator-wiki/0.1 (weekly site build; github.com/CheatingChicken/x4-ship-evaluator-wiki)";
// Page files the site serves. wiki.js is left out on purpose: the page reads the prebuilt data
// (data.js + data/*.json); live wiki requests could not work from github.io anyway (CORS).
const PAGE = ["index.html", "style.css", "app.js", "optimiser.js", "profile.js", "presets.js", "setup.js", "savereader.js"];

async function liveFetch(url) {
  for (let attempt = 0; ; attempt++) {
    try {
      const r = await fetch(url, { headers: { "User-Agent": UA, Accept: "application/json" } });
      if (r.status === 404) return null;
      if (!r.ok) throw new Error("HTTP " + r.status + " " + url);
      return await r.json();
    } catch (e) {
      if (attempt >= 1) throw e;
      await new Promise((res) => setTimeout(res, 2000));
    }
  }
}

const hash = (buf) => crypto.createHash("sha256").update(buf).digest("hex").slice(0, 10);

(async () => {
  const fixtures = args.includes("--fixtures");
  const supplement = JSON.parse(fs.readFileSync(path.join(ROOT, "supplement", "supplement.json"), "utf-8"));
  let last = 0;
  const data = await W.build({
    fetchJson: fixtures ? fixtureFetch : liveFetch, supplement, config: { concurrency: 4 }, origins: true,
    onProgress: (p) => { if (p.done - last >= 100 || p.done === p.total) { last = p.done; console.log(`${p.phase}: ${p.done}/${p.total}`); } },
  });
  data.meta.prebuilt = true;
  data.meta.built_from = fixtures ? "recorded wiki copy" : "live wiki";
  if (data.ships.length < 100 || data.parts.length < 200) throw new Error(`suspiciously little data (${data.ships.length} ships, ${data.parts.length} parts); not publishing`);
  // A part or ship defined by two mods belongs to the later one, so it is missing when that mod is
  // switched off. None today; worth knowing when it starts (a GitHub Actions warning).
  for (const id of data.meta.notes.defined_twice || []) console.log(`::warning::${id} is defined by more than one mod; the site lists it under the later one only`);
  const { manifest, chunks } = S.split(data, W.MODS);

  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(path.join(OUT, "data"), { recursive: true });
  // per-mod data, named in the manifest with its hash
  for (const m of manifest.mods) {
    const buf = Buffer.from(JSON.stringify(chunks[m.id]));
    fs.writeFileSync(path.join(OUT, "data", m.id + ".json"), buf);
    Object.assign(m, { file: `data/${m.id}.json?v=${hash(buf)}`, bytes: buf.length });
  }
  fs.writeFileSync(path.join(OUT, "data.js"),
    "// GENERATED by tools/build_site.js from the SWI wiki's data and supplement.json. Do not edit.\n" +
    "// The manifest of the per-mod data files, then the loader that merges them (evaluator/site_loader.js).\n" +
    "window.X4SITE = " + JSON.stringify(manifest) + ";\n" + fs.readFileSync(path.join(ROOT, "evaluator", "site_loader.js"), "utf-8"));
  for (const f of PAGE) fs.copyFileSync(path.join(ROOT, "evaluator", f), path.join(OUT, f));
  // The published site has no local server: its sections (Game data: re-export from the game
  // files) are cut from the page, not just hidden. The data is rebuilt by this script instead.
  const indexFile = path.join(OUT, "index.html");
  const html = fs.readFileSync(indexFile, "utf-8");
  let page = html.replace(/\s*<section class="server-only"[^>]*>[\s\S]*?<\/section>/g, "");
  if (page === html) throw new Error("index.html: no server-only section found to remove (markup changed?)");
  // cache busting: every file this build wrote that the page references
  const versioned = [];
  page = page.replace(/(src|href)="([^"?#:]+)"/g, (all, attr, file) => {
    const f = path.join(OUT, file);
    if (!fs.existsSync(f)) return all;            // optional scripts (player.js, wiki.js, ...)
    versioned.push(file);
    return `${attr}="${file}?v=${hash(fs.readFileSync(f))}"`;
  });
  for (const f of ["data.js", "app.js", "style.css"]) if (!versioned.includes(f)) throw new Error(`index.html: ${f} not found to version (markup changed?)`);
  fs.writeFileSync(indexFile, page);
  fs.copyFileSync(path.join(ROOT, "supplement", "supplement.json"), path.join(OUT, "supplement.json"));
  fs.writeFileSync(path.join(OUT, ".nojekyll"), "");
  const kb = (n) => Math.round(n / 1024) + " KB";
  console.log(`site in ${path.relative(ROOT, OUT) || "."} (${data.meta.built_from}): ${data.ships.length} ships, ${data.parts.length} parts; data.js ${kb(fs.statSync(path.join(OUT, "data.js")).size)}, ` +
    manifest.mods.map((m) => `${m.id} ${m.ships} ships/${m.parts} parts ${kb(m.bytes)}`).join(", "));
})().catch((e) => { console.error(e.message || e); process.exit(1); });
